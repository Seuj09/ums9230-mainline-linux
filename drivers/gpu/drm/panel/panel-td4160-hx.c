/*
 * Panel driver for the 720x1612 TD4160 panel in the Infinix X6525
 * (lcd_name=lcd_td4160_hx_mipi_hdp_x6525, sprd,lcm_ic_vendor="HX", 6.56").
 *
 * Not yet run on hardware.
 *
 * Everything panel-specific here now comes from this device's own board device
 * tree (dtbo entry 18) rather than from a sibling panel: the init sequence, the
 * reset sequences and the mode timings. The sequence can be regenerated at any
 * time with:
 *
 *   python3 -I tools/dtbo-extract.py dtbo.img -n 18 -x board.dtb
 *   python3 -I tools/dtb-dump.py board.dtb -n lcd_td4160_hx_mipi_hdp_x6525 \
 *       -p sprd,initial-command -r | python3 -I tools/lcd-dtsi-to-c.py --stream
 *
 * The board DT carries four panel nodes (td4160_txd, td4160_hx, ft8057s_dpt
 * and a dummy), each with its own sprd,initial-command; only the HX node's
 * 44 packets belong here.
 *
 * Timings: display-timings/timing0 is the native mode (native-mode = <0x02>).
 * Its totals give 60.03 Hz at the declared pixel clock:
 *   (720+155+4+80) * (1612+1020+4+32) * 60.03 = 153.6e6
 *
 * Not handled here (unrelated to the panel):
 *   - Charging: the AW32257 reads back as a bq24158 and is driven by mainline's
 *     bq2415x_charger (see the board DTS).
 *   - The board has no PWM backlight - brightness goes into the panel over DCS
 *     with a 12-bit range (sprd,max-level = 0xfff). A DCS backlight is
 *     implemented below; the vendor's brightness-level curve is not reproduced.
 *
 * First things to check if the panel stays dark: the reset polarity (the vendor
 * DT says active-high on ap_gpio 50, the reeder driver uses active-low) and the
 * backlight level (the init sequence ends on 0x51 0x00 0x00, i.e. brightness 0).
 */

